def columns(rows):
    assert len(rows) == 7 and all(len(r) == 5 and set(r) <= {"#", "."} for r in rows), rows
    return [sum(1 << y for y in range(7) if rows[y][x] == "#") for x in range(5)]


def main():
    missing = [chr(c) for c in range(0x20, 0x7F) if chr(c) not in GLYPHS]
    if missing:
        sys.exit(f"missing glyphs: {missing!r}")
    out = [
        "#pragma once",
        "",
        "// Generated by tools/gen_font5x7.py from the glyph drawings in that script. Do not edit.",
        "// Printable ASCII 0x20..0x7E, 5 column bytes per glyph, bit 0 = top row.",
        "",
        "#include <array>",
        "#include <cstdint>",
        "",
        "namespace core::font5x7 {",
        "",
        "inline constexpr char kFirst = 0x20;",
        "inline constexpr char kLast = 0x7E;",
        "inline constexpr std::array<uint8_t, (kLast - kFirst + 1) * 5> kGlyphs{",
    ]
    for c in range(0x20, 0x7F):
        cols = ", ".join(f"0x{b:02X}" for b in columns(GLYPHS[chr(c)]))
        label = "space" if c == 0x20 else ("backslash" if chr(c) == "\\" else chr(c))
        out.append(f"    {cols},  // {label}")
    out += ["};", "", "}  // namespace core::font5x7", ""]
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main()
